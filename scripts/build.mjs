import {mkdir,cp,readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {areaSummary} from '../model-plan.mjs';
import {writeReport} from './report.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
for(const file of ['app.js','model-plan.mjs'])execFileSync(process.execPath,['--check',file],{cwd:root,stdio:'inherit'});
execFileSync(process.execPath,['--test','tests/geometry.test.mjs','tests/viewer.test.mjs'],{cwd:root,stdio:'inherit'});
await writeReport();
await mkdir(new URL('../dist/',import.meta.url),{recursive:true});
for(const file of ['index.html','app.js','model-plan.mjs','style.css','plan.png','vendor','CORRECTED-PLAN-REPORT.md'])await cp(new URL('../'+file,import.meta.url),new URL('../dist/'+file,import.meta.url),{recursive:true});
const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
if(!html.includes('model-plan')&&!html.includes('app.js'))throw new Error('Missing viewer entry point');
await writeFile(new URL('../dist/area-summary.json',import.meta.url),JSON.stringify(areaSummary(),null,2)+'\n');
console.log('Build succeeded: static website in dist/. Main-house footprint:',areaSummary().main,'sq ft.');
